export const PLACEMENT_ALLOWLIST = ['market', 'eco-payoff', 'about-data'] as const;

export type PageLane = 'wiki' | 'tool' | 'secondary' | 'future';

/**
 * 全站页面登记（issue 283）。新增页面只改这里，再在 src/app/pageRegistry.tsx 补上同名懒加载。
 * 首页分组和导航分组目前是同一个 group，不在这里拆（issue 272）。
 */
export interface PageDef {
  key: string;
  /** 路由 pattern，与 <Route path> 一致 */
  path: string;
  kind: 'page' | 'redirect' | 'detail';
  /** 有 lane 才进入导航、首页和搜索里的页面结果 */
  lane?: PageLane;
  group?: SectionGroup;
  label?: string;
  en?: string;
  icon?: IconName;
  desc?: string;
  match?: RegExp;
  status?: 'planned';
  /** 不作为顶部百科快捷入口；分组工具菜单仍收录 */
  hideNav?: boolean;
  /** 404「你是不是要找」的常见写法 / 旧路径 */
  aliases?: readonly string[];
  /** 全局搜索俗称 */
  searchAliases?: readonly string[];
  /** 新页面可随登记表提供拼音，无需改动实体生成数据。 */
  searchPy?: { py: string; pyi: string };
  metaTitle?: string;
  metaDescription?: string;
  component?: ComponentId;
  redirectTo?: string;
  /** /tree 跳到默认文明科技树 */
  redirectDefaultTree?: boolean;
  /** 分享用的 og:url 不带查询（复盘、团战计划） */
  omitShareSearch?: boolean;
  /** 不进首页也不进导航时必须写原因。缺省且无 lane 的页面只能出现在 PLACEMENT_ALLOWLIST。 */
  entry?: 'none';
  entryReason?: string;
}

