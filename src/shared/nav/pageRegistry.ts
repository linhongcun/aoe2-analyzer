/** 有首页或导航位置，或显式 entry: 'none' 并写了原因。允许清单里的已知缺口另计。 */
export function hasEntryPlacement(page: PageDef): boolean {
  if (page.entry === 'none') return Boolean(page.entryReason?.trim());
  return Boolean(page.lane && page.group);
}
