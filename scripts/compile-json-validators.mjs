import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import standalone from 'ajv/dist/standalone/index.js';
import { format, resolveConfig } from 'prettier';
import { createSchemaCompiler, SCHEMA_ID_BASE } from './content-schema.mjs';

const output = resolve(dirname(fileURLToPath(import.meta.url)), '../src/content/schema/compiled');
const targets = [
  ['construction', 'data-construction.json', "import type { CompactConstructionData } from '../../../data/construction';", 'CompactConstructionData'],
  ['garrison-healing', 'data-garrison-healing.json', "import type { GarrisonHealingData } from '../../../domain/garrisonHealing';", 'GarrisonHealingData'],
  ['scouting', 'content-scouting.json', "import type { ScoutingContent } from '../../../domain/scouting';", 'ScoutingContent'],
  ['page-metadata', 'data-page-metadata.json', "import type { PageMeta } from '../../../domain/sharePage';", 'Record<string, PageMeta>'],
  ['team-bonuses', 'data-team-bonuses.json', "import type { TeamBonusData } from '../../../domain/teamBonuses';", 'TeamBonusData'],
];

// Ajv's standalone output uses require for a few tiny string/equality helpers.
// Convert those literal dependencies to ESM; the compiler itself is not shipped.
function esmHelpers(source) {
  const imports = [];
  const code = source.replace(/const ([a-zA-Z0-9_$]+) = require\("(ajv\/dist\/runtime\/[^".]+)"\)\.default;/gu, (_, name, path) => {
    imports.push(`import ${name}Module from '${path}.js';\nconst ${name} = ${name}Module.default ?? ${name}Module;`);
    return '';
  });
  if (/\brequire\(/u.test(code)) throw new Error('Unexpected non-ESM standalone dependency');
  return imports.join('\n') + '\n' + code;
}

export async function generateValidators(check = false) {
  mkdirSync(output, { recursive: true });
  const prettierOptions = (await resolveConfig(resolve(output, 'construction.mjs'))) ?? {};
  const changed = [];
  for (const [name, schema, typeImport, type] of targets) {
    // A fresh compiler and just its closure keep output independent of unrelated
    // registry additions and avoid bringing the whole schema set into browsers.
    const ajv = createSchemaCompiler({ standalone: true, schemaFiles: ['common.defs.json', schema] });
    const validate = ajv.getSchema(SCHEMA_ID_BASE + schema);
    if (!validate) throw new Error(`Missing runtime schema: ${schema}`);
    const code = `// Generated by scripts/compile-json-validators.mjs. Do not edit.\nimport { publicFormats } from '../policy.mjs';\n${esmHelpers(standalone(ajv, validate))}`;
    const declaration = `${typeImport}\nimport type { JsonValidator } from '../../../data/validatedJson';\ndeclare const validate: JsonValidator<${type}>;\nexport { validate };\nexport default validate;\n`;
    for (const [extension, content] of [
      ['mjs', code],
      ['d.mts', declaration],
    ]) {
      const file = resolve(output, `${name}.${extension}`);
      const expected = await format(content, { ...prettierOptions, filepath: file });
      if (!existsSync(file) || readFileSync(file, 'utf8') !== expected) {
        changed.push(file);
        if (!check) writeFileSync(file, expected);
      }
    }
  }
  if (check && changed.length) throw new Error(`JSON validators 不可复现：运行 npm run content:validators\n${changed.join('\n')}`);
  console.log(`JSON standalone validators：${targets.length} 个边界，${check ? '复现一致' : '生成完成'}`);
}

if (import.meta.url === pathToFileURL(resolve(process.argv[1] ?? '')).href) {
  if (process.argv.slice(2).some((argument) => argument !== '--check')) throw new Error('Unknown validator generation argument');
  await generateValidators(process.argv.includes('--check'));
}
